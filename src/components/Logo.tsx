import white320 from '@/assets/brand/logo-white-320.webp'
import white640 from '@/assets/brand/logo-white-640.webp'
import black320 from '@/assets/brand/logo-black-320.webp'
import black640 from '@/assets/brand/logo-black-640.webp'
import { cn } from '@/lib/cn'

export type LogoVariant = 'white' | 'black'

const sources: Record<LogoVariant, [string, string]> = {
  white: [white320, white640],
  black: [black320, black640],
}

/**
 * The only place the logo files are used.
 * - `white`: navbar, footer and any dark background.
 * - `black`: light backgrounds only.
 * Rasters are trimmed, alpha-transparent WebP generated by scripts/optimize-assets.py.
 * TODO(logo-svg): swap for the official SVG (white and black) when the client delivers it;
 * only this file changes.
 */
export function Logo({
  variant,
  className,
  priority = false,
}: {
  variant: LogoVariant
  className?: string
  priority?: boolean
}) {
  const [small, large] = sources[variant]
  return (
    <img
      src={small}
      srcSet={`${small} 320w, ${large} 640w`}
      sizes="(min-width: 768px) 200px, 140px"
      alt="Havana Barbería"
      width={320}
      height={204}
      decoding="async"
      {...(priority ? { fetchpriority: 'high' } : { loading: 'lazy' as const })}
      className={cn('h-auto w-[132px] select-none', className)}
    />
  )
}
