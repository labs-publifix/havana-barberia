// Bundles the site's pure booking rules for the Edge Functions (Deno can't read
// the "@/" alias or date-fns from node_modules). Output is committed:
// supabase/functions/_shared/engine.js. Run: npm run engine
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export async function bundleEngine() {
  const root = fileURLToPath(new URL('..', import.meta.url))
  const out = await build({
    entryPoints: [`${root}scripts/booking-engine.entry.ts`],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    tsconfig: `${root}tsconfig.app.json`,
    legalComments: 'none',
    write: false,
    absWorkingDir: root,
  })
  return `// GENERATED by scripts/build-engine.mjs from src/lib (availability, time, phone). Do not edit.\n${out.outputFiles[0].text}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await bundleEngine()
  writeFileSync(new URL('../supabase/functions/_shared/engine.js', import.meta.url), code)
  console.log('supabase/functions/_shared/engine.js', code.length, 'bytes')
}
